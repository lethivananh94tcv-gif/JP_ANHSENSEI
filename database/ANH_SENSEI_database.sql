CREATE TABLE IF NOT EXISTS roles (
    role_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name            VARCHAR(30) NOT NULL UNIQUE,
    description          VARCHAR(255),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_roles_name CHECK (role_name IN ('LEARNER', 'ADMIN'))
);

CREATE TABLE IF NOT EXISTS users (
    user_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id              BIGINT NOT NULL REFERENCES roles(role_id),
    email                VARCHAR(320) NOT NULL,
    password_hash        VARCHAR(255) NOT NULL,
    full_name            VARCHAR(150) NOT NULL,
    avatar_url           TEXT,
    target_level         VARCHAR(10),
    timezone             VARCHAR(100) NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
    status               VARCHAR(30) NOT NULL DEFAULT 'PENDING_VERIFICATION',
    email_verified_at    TIMESTAMPTZ,
    failed_login_count   INTEGER NOT NULL DEFAULT 0,
    lock_until           TIMESTAMPTZ,
    last_login_at        TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at           TIMESTAMPTZ,
    CONSTRAINT ck_users_email_lower CHECK (email = LOWER(BTRIM(email))),
    CONSTRAINT ck_users_target_level CHECK (target_level IS NULL OR target_level IN ('N5','N4','N3','N2','N1')),
    CONSTRAINT ck_users_status CHECK (status IN ('PENDING_VERIFICATION','ACTIVE','LOCKED','DISABLED','ARCHIVED')),
    CONSTRAINT ck_users_failed_login CHECK (failed_login_count >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_active
    ON users (LOWER(email)) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_users_role ON users(role_id);
CREATE INDEX IF NOT EXISTS ix_users_status ON users(status);

CREATE TABLE IF NOT EXISTS refresh_tokens (
    token_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
