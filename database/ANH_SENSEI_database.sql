CREATE TABLE IF NOT EXISTS questions (
    question_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id               BIGINT NOT NULL REFERENCES quizzes(quiz_id) ON DELETE CASCADE,
    question_type         VARCHAR(30) NOT NULL,
    prompt                TEXT NOT NULL,
    correct_answer        JSONB NOT NULL,
    explanation           TEXT,
    weight                NUMERIC(8,2) NOT NULL DEFAULT 1.00,
    audio_url             TEXT,
    sort_order            INTEGER NOT NULL,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_questions_type CHECK (question_type IN ('SINGLE_CHOICE','MULTIPLE_CHOICE','TRUE_FALSE','TEXT','FILL_BLANK','MATCHING')),
    CONSTRAINT ck_questions_weight CHECK (weight > 0),
    CONSTRAINT ck_questions_sort CHECK (sort_order > 0),
    UNIQUE (quiz_id, sort_order)
);

CREATE TABLE IF NOT EXISTS question_options (
    option_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id           BIGINT NOT NULL REFERENCES questions(question_id) ON DELETE CASCADE,
    option_text           TEXT NOT NULL,
    is_correct            BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order            INTEGER NOT NULL,
    CONSTRAINT ck_question_options_sort CHECK (sort_order > 0),
    UNIQUE (question_id, sort_order)
);

CREATE TABLE IF NOT EXISTS quiz_attempts (
    attempt_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT NOT NULL REFERENCES users(user_id),
    quiz_id               BIGINT NOT NULL REFERENCES quizzes(quiz_id),
    attempt_number        INTEGER NOT NULL,
    score                 NUMERIC(5,2),
    correct_count         INTEGER NOT NULL DEFAULT 0,
    total_count           INTEGER NOT NULL DEFAULT 0,
    started_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    submitted_at          TIMESTAMPTZ,
    status                VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS',
    submission_key        UUID NOT NULL DEFAULT gen_random_uuid(),
    CONSTRAINT ck_attempt_number CHECK (attempt_number > 0),
    CONSTRAINT ck_attempt_score CHECK (score IS NULL OR score BETWEEN 0 AND 100),
    CONSTRAINT ck_attempt_counts CHECK (correct_count >= 0 AND total_count >= 0 AND correct_count <= total_count),
    CONSTRAINT ck_attempt_status CHECK (status IN ('IN_PROGRESS','SUBMITTED','EXPIRED','ABANDONED')),
    CONSTRAINT ck_attempt_submission CHECK ((status = 'SUBMITTED' AND submitted_at IS NOT NULL AND score IS NOT NULL) OR status <> 'SUBMITTED'),
    UNIQUE (user_id, quiz_id, attempt_number),
    UNIQUE (submission_key)
);

CREATE INDEX IF NOT EXISTS ix_attempts_user_quiz ON quiz_attempts(user_id, quiz_id, started_at DESC);

CREATE TABLE IF NOT EXISTS quiz_attempt_answers (
    attempt_answer_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id                       BIGINT NOT NULL REFERENCES quiz_attempts(attempt_id) ON DELETE CASCADE,
    question_id                      BIGINT NOT NULL REFERENCES questions(question_id),
    selected_option_id               BIGINT REFERENCES question_options(option_id),
    text_answer                      TEXT,
    is_correct                       BOOLEAN NOT NULL DEFAULT FALSE,
    earned_score                     NUMERIC(8,2) NOT NULL DEFAULT 0,
    question_prompt_snapshot         TEXT NOT NULL,
    user_answer_snapshot             JSONB NOT NULL,
    correct_answer_snapshot          JSONB NOT NULL,
    explanation_snapshot             TEXT,
    answered_at                      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_attempt_answer_score CHECK (earned_score >= 0),
    UNIQUE (attempt_id, question_id)
);

