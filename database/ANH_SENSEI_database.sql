CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DO $$
DECLARE
    table_name TEXT;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'users','levels','lessons','vocabulary','kanji','grammar_points',
        'examples','quizzes','reading_contents','listening_contents','questions',
        'learning_progress','user_streaks','flashcard_progress','import_jobs',
        'knowledge_documents','chat_sessions','study_reminders'
    ]
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%I_updated_at ON %I', table_name, table_name);
        EXECUTE format(
            'CREATE TRIGGER trg_%I_updated_at BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
            table_name, table_name
        );
    END LOOP;
END;
$$;

-- Submitted attempts and their answer snapshots are immutable.
CREATE OR REPLACE FUNCTION protect_submitted_attempt()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.status = 'SUBMITTED' THEN
        RAISE EXCEPTION 'Submitted quiz attempts are immutable';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_protect_submitted_attempt ON quiz_attempts;
CREATE TRIGGER trg_protect_submitted_attempt
BEFORE UPDATE OR DELETE ON quiz_attempts
FOR EACH ROW EXECUTE FUNCTION protect_submitted_attempt();

CREATE OR REPLACE FUNCTION protect_submitted_answer()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_status VARCHAR(20);
BEGIN
    SELECT status INTO v_status
    FROM quiz_attempts
    WHERE attempt_id = OLD.attempt_id;

    IF v_status = 'SUBMITTED' THEN
        RAISE EXCEPTION 'Answers of a submitted attempt are immutable';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_protect_submitted_answer ON quiz_attempt_answers;
CREATE TRIGGER trg_protect_submitted_answer
BEFORE UPDATE OR DELETE ON quiz_attempt_answers
FOR EACH ROW EXECUTE FUNCTION protect_submitted_answer();

