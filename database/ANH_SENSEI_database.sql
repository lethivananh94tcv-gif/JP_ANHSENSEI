-- A quiz can belong to only one owner: a lesson directly, reading, or listening.
CREATE OR REPLACE FUNCTION check_quiz_exclusive_owner(p_quiz_id BIGINT)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
    SELECT
        (CASE WHEN EXISTS (SELECT 1 FROM quizzes q WHERE q.quiz_id = p_quiz_id AND q.lesson_id IS NOT NULL) THEN 1 ELSE 0 END) +
        (CASE WHEN EXISTS (SELECT 1 FROM reading_contents r WHERE r.quiz_id = p_quiz_id) THEN 1 ELSE 0 END) +
        (CASE WHEN EXISTS (SELECT 1 FROM listening_contents l WHERE l.quiz_id = p_quiz_id) THEN 1 ELSE 0 END)
        <= 1;
$$;

CREATE OR REPLACE FUNCTION enforce_quiz_exclusive_owner()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_quiz_id BIGINT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_quiz_id := OLD.quiz_id;
    ELSE
        v_quiz_id := NEW.quiz_id;
    END IF;

    IF v_quiz_id IS NOT NULL AND NOT check_quiz_exclusive_owner(v_quiz_id) THEN
        RAISE EXCEPTION 'Quiz % may belong to only one owner', v_quiz_id;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_quiz_owner_on_quiz ON quizzes;
CREATE CONSTRAINT TRIGGER trg_quiz_owner_on_quiz
AFTER INSERT OR UPDATE OR DELETE ON quizzes
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION enforce_quiz_exclusive_owner();

